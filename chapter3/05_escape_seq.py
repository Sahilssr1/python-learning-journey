print("Hello\nWorld")
# \n → new line
# Output:
# Hello
# World


print("Hello\tWorld")
# \t → tab space
# Output:
# Hello    World


print("He said \"Hello\"")
# \" → double quote
# Output:
# He said "Hello"


print("It's Sahil")
# ' → apostrophe can be used directly inside double quotes

print("C:\\Users\\Sahil")
# \\ → backslash
# Output:
# C:\Users\Sahil



# | Code | Meaning       |
# | ---- | ------------- |
# | `\n` | New line      |
# | `\t` | Tab           |
# | `\\` | Backslash `\` |
# | `\"` | Double quote  |
# | `\'` | Single quote  |
